// ─────────────────────────────────────────────────────────────────────────────
// FILTER ENUM
// ─────────────────────────────────────────────────────────────────────────────

enum _RFilter { all, today, high, ai }

extension _RFilterX on _RFilter {
  String get label {
    switch (this) {
      case _RFilter.all:
        return 'Tất cả';
      case _RFilter.today:
        return '📅 Hôm nay';
      case _RFilter.high:
        return '🔴 Khẩn';
      case _RFilter.ai:
        return '⚡ AI';
    }
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// PAGE
// ─────────────────────────────────────────────────────────────────────────────

class RemindersListPage extends StatefulWidget {
  final String currentUserId;
  final String? conversationId;
  final String? peerName;

  const RemindersListPage({
    super.key,
    required this.currentUserId,
    this.conversationId,
    this.peerName,
  });

  @override
  State<RemindersListPage> createState() => _RemindersListPageState();
}

class _RemindersListPageState extends State<RemindersListPage>
    with TickerProviderStateMixin {
  late final AnimationController _headerAnim;
  late final AnimationController _listAnim;

  _RFilter _filter = _RFilter.all;
  bool _showDone = false;
  bool _isLoading = false;

  // AI suggestions
  List<ReminderSuggestion> _suggestions = [];
  bool _loadingSuggestions = false;

  @override
  void initState() {
    super.initState();
    _headerAnim = AnimationController(
        vsync: this, duration: const Duration(milliseconds: 600))
      ..forward();
    _listAnim = AnimationController(
        vsync: this, duration: const Duration(milliseconds: 400))
      ..forward();

    WidgetsBinding.instance.addPostFrameCallback((_) => _loadSuggestions());
  }

  @override
  void dispose() {
    _headerAnim.dispose();
    _listAnim.dispose();
    super.dispose();
  }

  // ── AI Suggestions ─────────────────────────────────────────────────────────

  Future<void> _loadSuggestions() async {
    if (!mounted) return;
    setState(() => _loadingSuggestions = true);
    try {
      final provider = context.read<ReminderProvider>();
      final existing = await _fetchCurrentReminders(provider);
      final suggestions = await provider.getAISuggestions(
        userId: widget.currentUserId,
        recentMessages: const [], // caller can pass real messages
        existingReminders: existing,
      );
      if (mounted) setState(() => _suggestions = suggestions.take(3).toList());
    } catch (_) {
    } finally {
      if (mounted) setState(() => _loadingSuggestions = false);
    }
  }

  Future<List<EnhancedReminder>> _fetchCurrentReminders(
      ReminderProvider p) async {
    try {
      final snap = await p.firebaseFirestore
          .collection('reminders')
          .where('userId', isEqualTo: widget.currentUserId)
          .where('isCompleted', isEqualTo: false)
          .limit(20)
          .get();
      return snap.docs
          .map((d) => EnhancedReminder.fromMap(d.id, d.data()))
          .toList();
    } catch (_) {
      return [];
    }
  }

  // ── Filters ────────────────────────────────────────────────────────────────

  List<EnhancedReminder> _apply(List<EnhancedReminder> all) {
    switch (_filter) {
      case _RFilter.all:
        return all;
      case _RFilter.today:
        final now = DateTime.now();
        return all.where((r) {
          final d = r.reminderTime;
          return d.year == now.year && d.month == now.month && d.day == now.day;
        }).toList();
      case _RFilter.high:
        return all.where((r) => r.priority == ReminderPriority.high).toList();
      case _RFilter.ai:
        return all.where((r) => r.isAutoGenerated).toList();
    }
  }

  // ── Actions ────────────────────────────────────────────────────────────────

  Future<void> _complete(String id, ThemePalette p) async {
    HapticFeedback.lightImpact();
    final ok = await context.read<ReminderProvider>().completeReminder(id);
    if (!mounted) return;
    _snackbar(ok ? '✅ Đã hoàn thành!' : '❌ Lỗi',
        color: ok ? const Color(0xFF22C55E) : p.dangerColor);
  }

  Future<void> _delete(String id, ThemePalette p) async {
    final ok = await showDialog<bool>(
      context: context,
      builder: (_) => _ConfirmDlg(palette: p),
    );
    if (ok != true || !mounted) return;
    await context.read<ReminderProvider>().deleteReminder(id);
    if (!mounted) return;
    _snackbar('🗑 Đã xóa nhắc nhở');
  }

  void _snoozeSheet(EnhancedReminder r) {
    HapticFeedback.lightImpact();
    final p = context.read<ThemeProvider>().palette;
    final theme = context.read<ThemeProvider>();
    showModalBottomSheet(
      context: context,
      backgroundColor: Colors.transparent,
      isScrollControlled: true,
      builder: (_) => _SnoozeSheet(
        reminder: r,
        palette: p,
        theme: theme,
        onSnooze: (opt) async {
          Navigator.pop(context);
          final ok = await context
              .read<ReminderProvider>()
              .snoozeReminder(r.id, option: opt);
          if (!mounted) return;
          _snackbar(
            ok ? '⏰ Đã hoãn: ${opt.label}' : '❌ Lỗi',
            color: ok ? const Color(0xFF6C63FF) : p.dangerColor,
          );
        },
      ),
    );
  }

  void _editSheet(EnhancedReminder r) {
    final p = context.read<ThemeProvider>().palette;
    final theme = context.read<ThemeProvider>();
    showModalBottomSheet(
      context: context,
      backgroundColor: Colors.transparent,
      isScrollControlled: true,
      useSafeArea: true,
      builder: (_) => _EditSheet(
        reminder: r,
        palette: p,
        theme: theme,
        onSave: (time, priority) async {
          Navigator.pop(context);
          await context.read<ReminderProvider>().updateReminder(
                reminderId: r.id,
                newReminderTime: time,
                priority: priority,
              );
          if (!mounted) return;
          _snackbar('✅ Đã cập nhật nhắc nhở', color: const Color(0xFF22C55E));
        },
      ),
    );
  }

  void _addSheet() {
    final p = context.read<ThemeProvider>().palette;
    final theme = context.read<ThemeProvider>();
    showModalBottomSheet(
      context: context,
      backgroundColor: Colors.transparent,
      isScrollControlled: true,
      useSafeArea: true,
      builder: (_) => _AddSheet(
        palette: p,
        theme: theme,
        userId: widget.currentUserId,
        conversationId: widget.conversationId,
        provider: context.read<ReminderProvider>(),
        onCreated: () {
          if (!mounted) return;
          _snackbar('✅ Đã tạo nhắc nhở!', color: const Color(0xFF22C55E));
          _loadSuggestions();
        },
      ),
    );
  }

  void _snackbar(String msg, {Color? color}) {
    if (!mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(SnackBar(
      content: Text(msg, style: const TextStyle(fontWeight: FontWeight.w600)),
      behavior: SnackBarBehavior.floating,
      backgroundColor: color,
      duration: const Duration(seconds: 2),
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
      margin: const EdgeInsets.fromLTRB(16, 0, 16, 16),
    ));
  }

  // ══════════════════════════════════════════════════════════════════════════
  // BUILD
  // ══════════════════════════════════════════════════════════════════════════

  @override
  Widget build(BuildContext context) {
    final theme = context.watch<ThemeProvider>();
    final p = theme.palette;

    return Theme(
      data: theme.isDark ? theme.darkTheme : theme.lightTheme,
      child: Scaffold(
        backgroundColor: p.background,
        body: Stack(children: [
          NestedScrollView(
            headerSliverBuilder: (_, inner) => [
              _AppBar(
                peerName: widget.peerName,
                palette: p,
                theme: theme,
                headerAnim: _headerAnim,
                showDone: _showDone,
                onToggleDone: () => setState(() => _showDone = !_showDone),
                filter: _filter,
                onFilter: (f) {
                  HapticFeedback.selectionClick();
                  setState(() => _filter = f);
                },
              ),
            ],
            body: StreamBuilder<List<EnhancedReminder>>(
              stream: context
                  .read<ReminderProvider>()
                  .getEnhancedRemindersStream(widget.currentUserId),
              builder: (_, snap) {
                if (snap.connectionState == ConnectionState.waiting &&
                    !snap.hasData) {
                  return _Skeleton(palette: p);
                }
                final all = snap.data ?? [];
                final filtered = _apply(all);
                return _Body(
                  all: all,
                  filtered: filtered,
                  showDone: _showDone,
                  suggestions: _suggestions,
                  loadingSugg: _loadingSuggestions,
                  userId: widget.currentUserId,
                  palette: p,
                  theme: theme,
                  provider: context.read<ReminderProvider>(),
                  onComplete: _complete,
                  onDelete: _delete,
                  onSnooze: _snoozeSheet,
                  onEdit: _editSheet,
                  onAddFromSugg: (sug) => _addFromSuggestion(sug, p, theme),
                );
              },
            ),
          ),
          if (_isLoading)
            Container(
              color: Colors.black26,
              child: Center(
                child: CircularProgressIndicator(
                    color: theme.primaryColor, strokeWidth: 2.5),
              ),
            ),
        ]),
        floatingActionButton: _FAB(
          primaryColor: theme.primaryColor,
          onTap: _addSheet,
        ),
      ),
    );
  }

  void _addFromSuggestion(
    ReminderSuggestion sug,
    ThemePalette p,
    ThemeProvider theme,
  ) {
    showModalBottomSheet(
      context: context,
      backgroundColor: Colors.transparent,
      isScrollControlled: true,
      useSafeArea: true,
      builder: (_) => _AddSheet(
        palette: p,
        theme: theme,
        userId: widget.currentUserId,
        conversationId: widget.conversationId,
        provider: context.read<ReminderProvider>(),
        prefillMessage: sug.task,
        prefillPriority: sug.priority,
        onCreated: () {
          if (!mounted) return;
          _snackbar('✅ Đã thêm nhắc nhở AI!', color: const Color(0xFF22C55E));
          setState(() => _suggestions.remove(sug));
        },
      ),
    );
  }
}

