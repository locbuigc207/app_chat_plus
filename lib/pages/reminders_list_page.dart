  final String? conversationId;
  final ReminderProvider provider;
  final String? prefillMessage;
  final ReminderPriority? prefillPriority;
  final VoidCallback onCreated;

  const _AddSheet({
    required this.palette,
    required this.theme,
    required this.userId,
    required this.provider,
    required this.onCreated,
    this.conversationId,
    this.prefillMessage,
    this.prefillPriority,
  });

  @override
  State<_AddSheet> createState() => _AddSheetState();
}

class _AddSheetState extends State<_AddSheet> {
  late final TextEditingController _msgCtrl;
  DateTime _time = DateTime.now().add(const Duration(hours: 1));
  ReminderPriority _priority = ReminderPriority.medium;
  ReminderCategory _category = ReminderCategory.other;
  ReminderRepeat _repeat = ReminderRepeat.none;
  bool _saving = false;

  @override
  void initState() {
    super.initState();
    _msgCtrl = TextEditingController(text: widget.prefillMessage ?? '');
    _priority = widget.prefillPriority ?? ReminderPriority.medium;
  }

  @override
  void dispose() {
    _msgCtrl.dispose();
    super.dispose();
  }

  Future<void> _save() async {
    if (_msgCtrl.text.trim().isEmpty) return;
    if (_time.isBefore(DateTime.now())) {
      ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('⚠️ Thời gian phải ở tương lai!')));
      return;
    }
    setState(() => _saving = true);
    try {
      final r = await widget.provider.scheduleReminder(
        userId: widget.userId,
        messageId: DateTime.now().millisecondsSinceEpoch.toString(),
        conversationId: widget.conversationId ?? '',
        reminderTime: _time,
        message: _msgCtrl.text.trim(),
        priority: _priority,
        category: _category,
        repeat: _repeat,
      );
      if (!mounted) return;
      Navigator.pop(context);
      if (r != null) widget.onCreated();
    } finally {
      if (mounted) setState(() => _saving = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final p = widget.palette;
    final t = widget.theme;
    return _SheetWrapper(
      palette: p,
      child: Column(
        mainAxisSize: MainAxisSize.min,
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          _SheetHeader(
            icon: Icons.add_alarm_rounded,
            title: 'Thêm nhắc nhở',
            color: t.primaryColor,
            palette: p,
          ),
          const SizedBox(height: 16),
          // Message input
          TextField(
            controller: _msgCtrl,
            maxLines: 3,
            style: TextStyle(color: p.textPrimary, fontSize: 14.5),
            decoration: InputDecoration(
              hintText: 'Nội dung nhắc nhở...',
              hintStyle: TextStyle(color: p.textHint),
              filled: true,
              fillColor: p.surfaceVariant,
              border: OutlineInputBorder(
                borderRadius: BorderRadius.circular(14),
                borderSide: BorderSide.none,
              ),
              focusedBorder: OutlineInputBorder(
                borderRadius: BorderRadius.circular(14),
                borderSide: BorderSide(color: t.primaryColor, width: 1.5),
              ),
            ),
          ),
          const SizedBox(height: 14),
          _DateTimePicker(
            time: _time,
            palette: p,
            theme: t,
            onChanged: (dt) => setState(() => _time = dt),
          ),
          const SizedBox(height: 14),
          _PrioritySelector(
            selected: _priority,
            palette: p,
            onChanged: (pr) => setState(() => _priority = pr),
          ),
          const SizedBox(height: 10),
          _CategorySelector(
            selected: _category,
            palette: p,
            theme: t,
            onChanged: (c) => setState(() => _category = c),
          ),
          const SizedBox(height: 10),
          _RepeatSelector(
            selected: _repeat,
            palette: p,
            theme: t,
            onChanged: (r) => setState(() => _repeat = r),
          ),
          const SizedBox(height: 20),
          _PrimaryButton(
            label: 'Tạo nhắc nhở',
            primaryColor: t.primaryColor,
            loading: _saving,
            onTap: _save,
          ),
        ],
      ),
    );
  }
}

