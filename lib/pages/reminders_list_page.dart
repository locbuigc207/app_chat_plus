class _Body extends StatelessWidget {
  final List<EnhancedReminder> all;
  final List<EnhancedReminder> filtered;
  final bool showDone;
  final List<ReminderSuggestion> suggestions;
  final bool loadingSugg;
  final String userId;
  final ThemePalette palette;
  final ThemeProvider theme;
  final ReminderProvider provider;
  final Future<void> Function(String, ThemePalette) onComplete;
  final Future<void> Function(String, ThemePalette) onDelete;
  final void Function(EnhancedReminder) onSnooze;
  final void Function(EnhancedReminder) onEdit;
  final void Function(ReminderSuggestion) onAddFromSugg;

  const _Body({
    required this.all,
    required this.filtered,
    required this.showDone,
    required this.suggestions,
    required this.loadingSugg,
    required this.userId,
    required this.palette,
    required this.theme,
    required this.provider,
    required this.onComplete,
    required this.onDelete,
    required this.onSnooze,
    required this.onEdit,
    required this.onAddFromSugg,
  });

  @override
  Widget build(BuildContext context) {
    final p = palette;
    if (filtered.isEmpty && !showDone && suggestions.isEmpty) {
      return _EmptyState(palette: p, theme: theme);
    }

    return CustomScrollView(
      physics:
          const BouncingScrollPhysics(parent: AlwaysScrollableScrollPhysics()),
      slivers: [
        // ── Stats bar ────────────────────────────────────────────────────
        SliverToBoxAdapter(
          child: _StatsBar(reminders: all, palette: p, theme: theme),
        ),

        // ── AI Suggestions ───────────────────────────────────────────────
        if (loadingSugg)
          SliverToBoxAdapter(
            child: _SuggestionSkeleton(palette: p),
          )
        else if (suggestions.isNotEmpty) ...[
          SliverToBoxAdapter(
            child: _SectionHdr(
              label: '✨ Gợi ý từ AI',
              color: theme.primaryColor,
              palette: p,
            ),
          ),
          SliverToBoxAdapter(
            child: SizedBox(
              height: 86,
              child: ListView.separated(
                scrollDirection: Axis.horizontal,
                padding: const EdgeInsets.fromLTRB(16, 0, 16, 0),
                itemCount: suggestions.length,
                separatorBuilder: (_, __) => const SizedBox(width: 10),
                itemBuilder: (_, i) => _SuggestionChip(
                  suggestion: suggestions[i],
                  primaryColor: theme.primaryColor,
                  palette: p,
                  onTap: () => onAddFromSugg(suggestions[i]),
                ),
              ),
            ),
          ),
          const SliverToBoxAdapter(child: SizedBox(height: 8)),
        ],

        // ── Due Soon ─────────────────────────────────────────────────────
        ..._section(
          items: filtered.where((r) => r.isDueSoon).toList(),
          label: '⚡ Sắp đến hạn',
          color: const Color(0xFFEF4444),
          p: p,
          theme: theme,
          context: context,
        ),

        // ── Overdue ──────────────────────────────────────────────────────
        ..._section(
          items: filtered.where((r) => r.isOverdue && !r.isDueSoon).toList(),
          label: '🚨 Quá hạn',
          color: const Color(0xFFDC2626),
          p: p,
          theme: theme,
          context: context,
        ),

        // ── High priority ─────────────────────────────────────────────────
        ..._section(
          items: filtered
              .where((r) =>
                  r.priority == ReminderPriority.high &&
                  !r.isDueSoon &&
                  !r.isOverdue)
              .toList(),
          label: '🔴 Ưu tiên cao',
          color: ReminderPriority.high.color,
          p: p,
          theme: theme,
          context: context,
        ),

        // ── Medium priority ───────────────────────────────────────────────
        ..._section(
          items: filtered
              .where((r) =>
                  r.priority == ReminderPriority.medium &&
                  !r.isDueSoon &&
                  !r.isOverdue)
              .toList(),
          label: '🟡 Ưu tiên trung bình',
          color: ReminderPriority.medium.color,
          p: p,
          theme: theme,
          context: context,
        ),

        // ── Low priority ──────────────────────────────────────────────────
        ..._section(
          items: filtered
              .where((r) =>
                  r.priority == ReminderPriority.low &&
                  !r.isDueSoon &&
                  !r.isOverdue)
              .toList(),
          label: '🟢 Ưu tiên thấp',
          color: ReminderPriority.low.color,
          p: p,
          theme: theme,
          context: context,
        ),

        // ── Completed ─────────────────────────────────────────────────────
        if (showDone) ...[
          SliverToBoxAdapter(
            child: _SectionHdr(
              label: '✅ Đã hoàn thành',
              color: const Color(0xFF22C55E),
              palette: p,
            ),
          ),
          SliverToBoxAdapter(
            child: StreamBuilder<List<EnhancedReminder>>(
              stream: provider.getCompletedRemindersStream(userId),
              builder: (_, snap) {
                final done = snap.data ?? [];
                if (done.isEmpty) {
                  return Padding(
                    padding: const EdgeInsets.all(20),
                    child: Text('Chưa có nhắc nhở hoàn thành',
                        style: TextStyle(color: p.textHint, fontSize: 13)),
                  );
                }
                return Column(
                  children: done
                      .map((r) => _RCard(
                            reminder: r,
                            palette: p,
                            theme: theme,
                            isCompleted: true,
                            onComplete: () {},
                            onSnooze: () {},
                            onDelete: () => onDelete(r.id, p),
                            onEdit: () {},
                          ))
                      .toList(),
                );
              },
            ),
          ),
        ],

        const SliverToBoxAdapter(child: SizedBox(height: 110)),
      ],
    );
  }

  List<Widget> _section({
    required List<EnhancedReminder> items,
    required String label,
    required Color color,
    required ThemePalette p,
    required ThemeProvider theme,
    required BuildContext context,
  }) {
    if (items.isEmpty) return [];
    return [
      SliverToBoxAdapter(
        child: _SectionHdr(
            label: label, color: color, count: items.length, palette: p),
      ),
      SliverList(
        delegate: SliverChildBuilderDelegate(
          (_, i) => _RCard(
            reminder: items[i],
            palette: p,
            theme: theme,
            onComplete: () => onComplete(items[i].id, p),
            onSnooze: () => onSnooze(items[i]),
            onDelete: () => onDelete(items[i].id, p),
            onEdit: () => onEdit(items[i]),
          ),
          childCount: items.length,
        ),
      ),
    ];
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// REMINDER CARD (Swipeable)
// ─────────────────────────────────────────────────────────────────────────────

class _RCard extends StatefulWidget {
  final EnhancedReminder reminder;
  final ThemePalette palette;
  final ThemeProvider theme;
  final bool isCompleted;
  final VoidCallback onComplete;
  final VoidCallback onSnooze;
  final VoidCallback onDelete;
  final VoidCallback onEdit;

  const _RCard({
    required this.reminder,
    required this.palette,
    required this.theme,
    required this.onComplete,
    required this.onSnooze,
    required this.onDelete,
    required this.onEdit,
    this.isCompleted = false,
  });

  @override
  State<_RCard> createState() => _RCardState();
}

class _RCardState extends State<_RCard> with SingleTickerProviderStateMixin {
  late final AnimationController _anim;
  bool _gone = false;

  @override
  void initState() {
    super.initState();
    _anim = AnimationController(
        vsync: this, duration: const Duration(milliseconds: 380))
      ..forward();
  }

  @override
  void dispose() {
    _anim.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    if (_gone) return const SizedBox.shrink();
    final r = widget.reminder;
    final p = widget.palette;
    final t = widget.theme;

    return FadeTransition(
      opacity: CurvedAnimation(parent: _anim, curve: Curves.easeOut),
      child: SlideTransition(
        position: Tween<Offset>(begin: const Offset(0.04, 0), end: Offset.zero)
            .animate(
                CurvedAnimation(parent: _anim, curve: Curves.easeOutCubic)),
        child: Dismissible(
          key: ValueKey(r.id),
          background: _SwipeBg(
              color: const Color(0xFF22C55E),
              icon: Icons.check_rounded,
              label: 'Xong',
              align: Alignment.centerLeft),
          secondaryBackground: _SwipeBg(
              color: const Color(0xFFEF4444),
              icon: Icons.delete_rounded,
              label: 'Xóa',
              align: Alignment.centerRight),
          onDismissed: (dir) {
            setState(() => _gone = true);
            if (dir == DismissDirection.startToEnd) {
              widget.onComplete();
            } else {
              widget.onDelete();
            }
          },
          child: _CardInner(
            r: r,
            p: p,
            t: t,
            isCompleted: widget.isCompleted,
            onEdit: widget.onEdit,
            onComplete: widget.onComplete,
            onSnooze: widget.onSnooze,
            onDelete: widget.onDelete,
          ),
        ),
      ),
    );
  }
}

class _CardInner extends StatelessWidget {
  final EnhancedReminder r;
  final ThemePalette p;
  final ThemeProvider t;
  final bool isCompleted;
  final VoidCallback onEdit;
  final VoidCallback onComplete;
  final VoidCallback onSnooze;
  final VoidCallback onDelete;

  const _CardInner({
    required this.r,
    required this.p,
    required this.t,
    required this.isCompleted,
