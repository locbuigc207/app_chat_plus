class _Skeleton extends StatefulWidget {
  final ThemePalette palette;
  const _Skeleton({required this.palette});

  @override
  State<_Skeleton> createState() => _SkeletonState();
}

class _SkeletonState extends State<_Skeleton>
    with SingleTickerProviderStateMixin {
  late final AnimationController _ctrl;
  late final Animation<double> _anim;

  @override
  void initState() {
    super.initState();
    _ctrl = AnimationController(
        vsync: this, duration: const Duration(milliseconds: 1100))
      ..repeat(reverse: true);
    _anim = CurvedAnimation(parent: _ctrl, curve: Curves.easeInOut);
  }

  @override
  void dispose() {
    _ctrl.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return AnimatedBuilder(
      animation: _anim,
      builder: (_, __) {
        final c = widget.palette.isDark
            ? Color.lerp(
                const Color(0xFF1A1A1A), const Color(0xFF252525), _anim.value)!
            : Color.lerp(
                const Color(0xFFEEEEEE), const Color(0xFFE4E4E4), _anim.value)!;
        return ListView.builder(
          padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 12),
          itemCount: 5,
          itemBuilder: (_, __) => Container(
            margin: const EdgeInsets.only(bottom: 10),
            height: 90,
            decoration: BoxDecoration(
                color: c, borderRadius: BorderRadius.circular(18)),
          ),
        );
      },
    );
  }
}

