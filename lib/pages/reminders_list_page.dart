    final now = DateTime.now();
    final diff = dt.difference(now);

    if (diff.isNegative) {
      final ago = now.difference(dt);
      if (ago.inMinutes < 60) return 'Quá hạn ${ago.inMinutes} phút';
      if (ago.inHours < 24) return 'Quá hạn ${ago.inHours} giờ';
      return 'Quá hạn ${DateFormat('dd/MM HH:mm').format(dt)}';
    }
    if (diff.inMinutes < 60) return 'Còn ${diff.inMinutes} phút';
    if (diff.inHours < 24) {
      if (dt.day == now.day) return 'Hôm nay ${DateFormat('HH:mm').format(dt)}';
    }
    if (dt.day == now.day + 1 && dt.month == now.month && dt.year == now.year)
      return 'Ngày mai ${DateFormat('HH:mm').format(dt)}';
    return DateFormat('HH:mm, dd/MM/yyyy').format(dt);
  }
